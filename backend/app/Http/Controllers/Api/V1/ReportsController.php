<?php

namespace App\Http\Controllers\Api\V1;

use App\Exceptions\ApiException;
use App\Http\Controllers\Controller;
use App\Models\UserAccount;
use App\Services\AuditService;
use App\Services\ReportsService;
use App\Support\Lists;
use App\Support\Scope;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;

/** /reports/* (role:admin,dept): the five report types and the export history. */
class ReportsController extends Controller
{
    private const FORMATS = ['pdf' => 'PDF', 'excel' => 'Excel', 'csv' => 'CSV'];

    /** The report's batch window (ReportsService::batches); without it, the last five batches. */
    private const BATCH_RULES = ['batch_from' => 'nullable|integer|between:1950,2100', 'batch_to' => 'nullable|integer|between:1950,2100'];

    private const HISTORY = <<<'SQL'
        SELECT e.export_id AS id, e.type, e.format, e.record_count AS "recordCount", e.scope_label AS "scopeLabel",
               e.status, e.created_at AS "createdAt", e.filters, COALESCE(u.display_name, 'Deleted user') AS "by"
          FROM report_export e LEFT JOIN user_account u ON u.user_id = e.generated_by
        SQL;

    public function __construct(
        private readonly ReportsService $reports,
        private readonly AuditService $audit,
    ) {}

    /** GET /reports/types */
    public function types(Request $request): JsonResponse
    {
        $last = $this->reports->lastRuns($this->scope($request));

        return response()->json(['data' => array_map(fn ($t) => $t + ['lastRun' => $last[$t['id']] ?? null], ReportsService::TYPES)]);
    }

    /** GET /reports/:type?college_id&program_id&batch_from&batch_to (default: the last five batches) */
    public function show(Request $request, string $type): JsonResponse
    {
        if (! in_array($type, ReportsService::typeIds(), true)) {
            throw ApiException::notFound('Unknown report type.');
        }
        $f = $request->validate(['college_id' => 'nullable|integer|min:1', 'program_id' => 'nullable|integer|min:1'] + self::BATCH_RULES);

        return response()->json($this->reports->data($this->scope($request), $type, $f));
    }

    /** GET /reports/exports?page&per_page: dept users see exports generated by accounts of their own college. */
    public function exports(Request $request): JsonResponse
    {
        $scope = $this->scope($request);
        [$page, $per] = Lists::paging($request, 10);
        $where = $scope->role === 'dept' ? 'WHERE u.college_id = ?' : '';
        $params = $scope->role === 'dept' ? [$scope->collegeId] : [];
        $total = (int) DB::selectOne("SELECT count(*) AS n FROM report_export e LEFT JOIN user_account u ON u.user_id = e.generated_by {$where}", $params)->n;
        $rows = DB::select(self::HISTORY." {$where} ORDER BY e.created_at DESC, e.export_id DESC LIMIT ? OFFSET ?", [...$params, $per, ($page - 1) * $per]);

        return response()->json(Lists::out(array_map(self::out(...), $rows), $total, $page, $per));
    }

    /** POST /reports/exports { type, format: pdf|excel|csv, college_id, program_id, batch_from, batch_to }: records an export built by the client. */
    public function storeExport(Request $request): JsonResponse
    {
        $b = $request->validate([
            'type' => 'required|in:'.implode(',', ReportsService::typeIds()),
            'format' => 'required|in:pdf,excel,csv,PDF,Excel,CSV',
            'college_id' => 'nullable|integer|min:1',
            'program_id' => 'nullable|integer|min:1',
        ] + self::BATCH_RULES);
        $scope = $this->scope($request);
        $format = strtolower($b['format']);
        $d = $this->reports->data($scope, $b['type'], $b);
        $id = DB::transaction(function () use ($request, $b, $scope, $format, $d) {
            $id = (int) DB::table('report_export')->insertGetId([
                'type' => $b['type'], 'format' => $format, 'generated_by' => $request->user() instanceof UserAccount ? $request->user()->user_id : null,
                'filters' => json_encode(['college_id' => $scope->role === 'dept' ? $scope->collegeId : ($b['college_id'] ?? null), 'program_id' => $b['program_id'] ?? null, 'batches' => $d['batchRange']]),
                'record_count' => $d['recordCount'], 'scope_label' => "{$d['scope']} · {$d['batchLabel']} · {$d['records']} records",
            ], 'export_id');
            $this->audit->log('export', 'report_export', $id, null, ['type' => $b['type'], 'format' => $format]);

            return $id;
        });

        return response()->json(self::out(DB::selectOne(self::HISTORY.' WHERE e.export_id = ?', [$id])), 201);
    }

    /** @return array<string, mixed> */
    private static function out(object $r): array
    {
        return ['id' => (int) $r->id, 'type' => $r->type, 'name' => collect(ReportsService::TYPES)->firstWhere('id', $r->type)['name'] ?? $r->type,
            'format' => $r->format, 'fmt' => self::FORMATS[$r->format] ?? $r->format, 'recordCount' => $r->recordCount, 'scopeLabel' => $r->scopeLabel,
            'status' => $r->status, 'createdAt' => $r->createdAt, 'filters' => json_decode((string) $r->filters, true), 'by' => $r->by];
    }

    private function scope(Request $request): Scope
    {
        $user = $request->user();

        return Scope::for($user instanceof UserAccount ? $user : null);
    }
}
