import { Router } from 'express';
import { z } from 'zod';
import { many, one, tx } from '../db/index.js';
import { requireRole } from '../middleware/auth.js';
import { validate } from '../middleware/common.js';
import { scopeFor } from '../middleware/scope.js';
import { id } from '../lib/validation.js';
import { audit, fromReq } from '../services/audit.js';
import { REPORT_TYPES, lastRuns, reportData } from '../services/reports.js';

const router = Router();
router.use(requireRole('admin', 'dept'));
const TYPES = REPORT_TYPES.map((t) => t.id);
const FORMATS = { PDF: 'pdf', Excel: 'excel', CSV: 'csv', pdf: 'pdf', excel: 'excel', csv: 'csv' };
const FORMAT_LABEL = { pdf: 'PDF', excel: 'Excel', csv: 'CSV' };

router.get('/types', async (req, res, next) => {
  try {
    const last = await lastRuns(req.user);
    res.json(REPORT_TYPES.map((t) => ({ ...t, lastRun: last[t.id] || null })));
  } catch (err) { next(err); }
});

const historySelect = `
  SELECT e.export_id AS id, e.report_type AS type, e.format, e.file_size AS "fileSize", e.record_count AS "recordCount", e.scope_label AS "scopeLabel",
         e.status, e.created_at AS "createdAt", e.filters, e.sections, COALESCE(u.display_name, 'Deleted user') AS "by"
    FROM report_export e LEFT JOIN user_account u ON u.user_id = e.generated_by`;

// Report history: dept users see exports generated by accounts of their own college.
router.get('/exports', validate({ query: z.object({ limit: z.coerce.number().int().min(1).max(100).default(10) }) }), async (req, res, next) => {
  try {
    const c = scopeFor(req.user).collegeId ?? null;
    const [rows, n] = await Promise.all([
      many(`${historySelect} WHERE ($1::bigint IS NULL OR u.college_id = $1) ORDER BY e.created_at DESC LIMIT ${req.valid.query.limit}`, [c]),
      one('SELECT count(*)::int AS n FROM report_export e LEFT JOIN user_account u ON u.user_id = e.generated_by WHERE ($1::bigint IS NULL OR u.college_id = $1)', [c]),
    ]);
    res.json({ rows: rows.map((r) => ({ ...r, fmt: FORMAT_LABEL[r.format], name: REPORT_TYPES.find((t) => t.id === r.type)?.name })), total: n.n });
  } catch (err) { next(err); }
});

router.post('/exports', validate({ body: z.object({
  type: z.enum(TYPES), format: z.enum(Object.keys(FORMATS)), collegeId: id.optional(), programId: id.optional(),
  sections: z.array(z.enum(['kpi', 'chart', 'table', 'findings'])).max(4).default([]), fileSize: z.number().int().min(0).max(1e9).optional(),
}) }), async (req, res, next) => {
  try {
    const b = req.valid.body;
    const d = await reportData(req.user, b.type, b);
    const row = await tx(async (db) => {
      const r = await one(
        `INSERT INTO report_export (generated_by, report_type, filters, sections, format, file_size, record_count, scope_label)
         VALUES ($1, $2, $3, $4, $5, $6, $7, $8) RETURNING export_id`,
        [req.user.user_id, b.type, JSON.stringify({ collegeId: scopeFor(req.user).collegeId ?? b.collegeId ?? null, programId: b.programId ?? null, batches: d.batchRange }),
          JSON.stringify(b.sections), FORMATS[b.format], b.fileSize ?? null, d.recordCount, `${d.scope} · ${d.batchLabel} · ${d.records} records`], db,
      );
      await audit(db, fromReq(req, { entityType: 'report_export', entityId: r.export_id, action: 'export', details: { type: b.type, format: FORMATS[b.format] } }));
      return one(`${historySelect} WHERE e.export_id = $1`, [r.export_id], db);
    });
    res.status(201).json({ ...row, fmt: FORMAT_LABEL[row.format], name: REPORT_TYPES.find((t) => t.id === row.type)?.name });
  } catch (err) { next(err); }
});

router.get('/:type', validate({ params: z.object({ type: z.enum(TYPES) }), query: z.object({ collegeId: id.optional(), programId: id.optional() }) }), async (req, res, next) => {
  try { res.json(await reportData(req.user, req.valid.params.type, req.valid.query)); } catch (err) { next(err); }
});

export default router;
